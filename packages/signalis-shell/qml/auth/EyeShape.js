function contains(x, y) {
    var inside = false;
    for (var i = 0, j = aperture.length - 1; i < aperture.length; j = i++) {
        var a = aperture[i], b = aperture[j];
        if ((a[1] > y) !== (b[1] > y)
                && x < (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]) + a[0])
            inside = !inside;
    }
    return inside;
}
